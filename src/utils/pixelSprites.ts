// Draw a pixel matrix on canvas
export function drawPixelMatrix(
  ctx: CanvasRenderingContext2D,
  matrix: string[],
  x: number,
  y: number,
  pixelSize: number,
  colorMap: Record<string, string>
) {
  for (let r = 0; r < matrix.length; r++) {
    const row = matrix[r];
    for (let c = 0; c < row.length; c++) {
      const char = row[c];
      if (char !== ' ' && char !== '.') {
        const color = colorMap[char] || colorMap['#'] || '#535353';
        ctx.fillStyle = color;
        ctx.fillRect(
          Math.floor(x + c * pixelSize),
          Math.floor(y + r * pixelSize),
          pixelSize,
          pixelSize
        );
      }
    }
  }
}

